/* Browser integration test: isolated database, synthetic media, paused queue. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { spawn, spawnSync } from 'node:child_process';
const playwrightModule = await import(pathToFileURL(createRequire(import.meta.url).resolve('playwright')).href);
const { chromium } = playwrightModule.default || playwrightModule;

async function main() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'reels-dashboard-'));
  process.env.DATA_DIR = dir;
  process.env.ADMIN_EMAIL = 'design@example.invalid';
  const databaseModule = await import('../src/services/database.ts');
  const d = databaseModule.default || databaseModule;
  d.initDatabase();
  d.getDb().prepare("UPDATE users SET name='Marina Oliveira',plan='pro' WHERE id=1").run();
  d.createSession('dashboard-browser', 1, new Date(Date.now() + 3600000));
  d.updateSettings(1, { facebook_enabled: true, instagram_enabled: false, auto_publish: false, facebook_page_id: 'test-page', facebook_page_name: 'Estúdio Editorial' });
  const source = d.createSource({ username: 'estudio.criativo', user_id: 1 });
  const media = path.join(dir, 'sample.mp4');
  const ffmpeg = spawnSync(process.env.FFMPEG_PATH || 'ffmpeg', ['-y', '-f', 'lavfi', '-i', 'testsrc2=size=270x480:rate=12', '-t', '2', '-c:v', 'libx264', '-threads', '2', '-pix_fmt', 'yuv420p', media], { encoding: 'utf8' });
  assert.equal(ffmpeg.status, 0, ffmpeg.stderr);
  const insert = d.getDb().prepare('INSERT INTO reels (user_id, source_id, source_username, instagram_url, instagram_id, caption, original_caption, stage, local_path, r2_url, duration_seconds, published_at) VALUES (?,?,?,?,?,?,?,?,?,?,?,?)');
  const captions = ['Registro histórico único', 'Uma nova perspectiva sobre a cidade', 'Bastidores de uma ideia que ganhou vida', 'Histórias que merecem ser compartilhadas', 'Pequenos detalhes, grandes descobertas'];
  for (let i = 0; i < 64; i++) {
    const stage = ['published','error','processing','uploaded','discovered'][i % 5];
    insert.run(1, source.id, ['estudio.criativo','olhares.urbanos','diario.visual'][i%3], `https://www.instagram.com/reel/browser${i}/`, `browser${i}`, (i === 0 ? captions[0] : captions[1+i%4] + ` · ${i}`), '', stage, i%3 === 0 || stage === 'uploaded' ? media : null, stage === 'uploaded' ? 'https://media.example.invalid/test.mp4' : null, 32 + i, stage === 'published' ? new Date().toISOString() : null);
  }
  insert.run(1, source.id, 'estudio.criativo', 'https://www.instagram.com/reel/pending/', 'pending', 'Nova pauta para produzir', '', 'discovered', null, null, 0, null);
  insert.run(1, source.id, 'estudio.criativo', 'https://www.instagram.com/reel/preview/', 'preview', 'Prévia da campanha', '', 'uploaded', media, 'https://media.example.invalid/test.mp4', 42, null);
  const pipelineModule = await import('../src/services/pipeline.ts');
  const queue = (pipelineModule.default || pipelineModule).getQueue();
  queue.setState('paused', 'true');
  const port = process.env.DASHBOARD_SMOKE_PORT || '3120';
  const base = `http://127.0.0.1:${port}`;
  const server = spawn(process.execPath, ['node_modules/next/dist/bin/next', 'start', '--hostname', '127.0.0.1', '--port', port], { env: { ...process.env, NODE_ENV: 'production' }, stdio: ['ignore','pipe','pipe'] });
  let logs = '';
  server.stdout.on('data', b => { logs = (logs + b).slice(-6000); });
  server.stderr.on('data', b => { logs = (logs + b).slice(-6000); });
  let browser;
  try {
    let ready = false;
    for (let i=0;i<100;i++) {
      if (server.exitCode !== null) throw new Error(logs);
      try { ready = (await fetch(base)).ok; } catch {}
      if (ready) break;
      await new Promise(r=>setTimeout(r,100));
    }
    assert.ok(ready, 'server must start');
    browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce', timezoneId: 'America/Sao_Paulo' });
    await context.addCookies([{ name: 'session', value: 'dashboard-browser', url: base }]);
    await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort());
    const page = await context.newPage();
    const errors=[];
    page.on('pageerror', e=>{errors.push(e.message);console.log('Browser error',e.message);});
    await page.goto(`${base}/dashboard`);
    try { await page.waitForSelector('video', { timeout: 10000 }); } catch(error) { console.log('Initial page diagnostics',await page.locator('body').innerText(),errors); throw error; }
    assert.ok(await page.locator('video[controls]').count() > 0, 'video cards must expose keyboard/touch playback controls');
    await page.getByRole('heading', { name: 'Biblioteca de vídeos' }).waitFor();
    if(process.env.DASHBOARD_SCREENSHOTS) {
      fs.mkdirSync(process.env.DASHBOARD_SCREENSHOTS,{recursive:true});
      await page.screenshot({path:path.join(process.env.DASHBOARD_SCREENSHOTS,'dashboard-initial.png'),fullPage:true});
    }
    const search = page.getByRole('searchbox', { name: 'Buscar vídeos' });
    await search.fill('Registro histórico único');
    try { await page.getByText('Registro histórico único', { exact: true }).waitFor({timeout:7000}); }
    catch(error) { console.log('Search diagnostics',await search.inputValue(),await page.locator('.library-footer').innerText(),await page.locator('[role=alert]').allTextContents(),await page.locator('.video-grid').innerText(),errors); throw error; }
    await search.fill('Uma busca que não existe');
    await page.getByText('Nenhum vídeo encontrado', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Limpar filtros' }).click();
    await page.getByRole('button', { name: 'Próxima página' }).click();
    await page.getByText(/Página 2 de/).waitFor();
    await page.getByRole('button', { name: 'Página anterior' }).click();
    await page.getByRole('button', { name: 'Adicionar vídeo', exact: true }).first().click();
    await page.getByRole('dialog').waitFor();
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({state:'hidden'});
    assert.ok(await page.getByRole('button',{name:'Adicionar vídeo',exact:true}).first().evaluate(el=>el===document.activeElement),'modal restores the triggering button');
    await page.getByRole('button',{name:'Adicionar vídeo',exact:true}).first().click();
    await page.getByRole('textbox',{name:'Link do vídeo'}).fill('https://www.instagram.com/reel/preview/');
    await page.getByRole('dialog').getByRole('button',{name:'Adicionar à fila',exact:true}).click();
    await page.getByRole('dialog').getByRole('alert').waitFor();
    assert.ok((await page.getByRole('dialog').getByRole('alert').innerText()).length>0,'duplicate video must display server error');
    await page.getByRole('dialog').getByRole('button',{name:'Cancelar',exact:true}).click();
    await page.getByRole('button',{name:'Adicionar vídeo',exact:true}).first().click();
    assert.equal(await page.getByRole('textbox',{name:'Link do vídeo'}).inputValue(),'','reopened modal clears previous data');
    assert.equal(await page.getByRole('dialog').getByRole('alert').count(),0,'reopened modal clears previous error');
    for(let i=0;i<8;i++) await page.keyboard.press('Tab');
    assert.ok(await page.getByRole('dialog').evaluate(el=>el.contains(document.activeElement)),'Tab focus stays inside dialog');
    await page.getByRole('textbox',{name:'Link do vídeo'}).fill('https://www.instagram.com/reel/new-browser-video/');
    await page.getByRole('textbox',{name:/Legenda própria/}).fill('Vídeo adicionado no teste');
    await page.getByRole('dialog').getByRole('button',{name:'Adicionar à fila',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    assert.equal(d.getDb().prepare("SELECT COUNT(*) n FROM reels WHERE caption='Vídeo adicionado no teste'").get().n,1);
    assert.equal(queue.db.prepare("SELECT COUNT(*) n FROM pipeline_jobs WHERE kind='prepare'").get().n,0,'add respects auto_publish=false');
    await search.fill('Prévia da campanha');
    await page.getByText('Prévia da campanha', { exact: true }).waitFor();
    const previewCard=page.getByRole('list',{name:'Vídeos',exact:true}).getByRole('listitem').filter({hasText:'Prévia da campanha'});
    const video=previewCard.locator('video');
    assert.equal(await video.evaluate(async el=>{ await el.play(); return el.paused; }), false);
    await video.evaluate(el=>el.pause());
    await previewCard.getByRole('button',{name:'Publicar',exact:true}).click();
    const dialog=page.getByRole('dialog');
    await dialog.waitFor();
    assert.equal(await dialog.getByRole('checkbox',{name:/Instagram/}).count(),0);
    await dialog.getByRole('button',{name:'Publicar vídeo',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    await page.getByRole('status').filter({hasText:'Publicação registrada na fila'}).first().waitFor();
    const jobs=queue.db.prepare("SELECT payload FROM pipeline_jobs WHERE kind='publish'").all();
    assert.ok(jobs.length > 0);
    assert.ok(jobs.every(j=>JSON.parse(j.payload).target==='facebook'));
    assert.equal(queue.state('paused'),'true');
    await search.fill('Nova pauta para produzir');
    await page.getByText('Nova pauta para produzir',{exact:true}).waitFor();
    await page.getByRole('button',{name:'Processar',exact:true}).click();
    assert.ok((await page.getByRole('dialog').innerText()).includes('também pode publicar'),'processing must disclose publication');
    assert.equal(queue.db.prepare("SELECT COUNT(*) n FROM pipeline_jobs WHERE kind='prepare'").get().n,0,'opening confirmation cannot enqueue work');
    await page.getByRole('dialog').getByRole('button',{name:'Processar vídeo',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    const prepare=queue.db.prepare("SELECT * FROM pipeline_jobs WHERE kind='prepare'").get();
    assert.equal(JSON.parse(prepare.payload).manual,true);
    await page.getByRole('button',{name:'Excluir reel',exact:true}).click();
    queue.db.prepare("UPDATE pipeline_jobs SET status='running' WHERE id=?").run(prepare.id);
    await page.getByRole('dialog').getByRole('button',{name:'Excluir vídeo',exact:true}).click();
    await page.getByRole('dialog').getByRole('alert').waitFor();
    assert.ok(d.getReelById(prepare.ref_id,1),'409 deletion conflict must retain the video');
    queue.db.prepare("UPDATE pipeline_jobs SET status='queued' WHERE id=?").run(prepare.id);
    await page.getByRole('dialog').getByRole('button',{name:'Excluir vídeo',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    assert.ok(!d.getReelById(prepare.ref_id,1),'successful delete removes video');
    assert.equal(queue.state('paused'),'true');
    assert.equal(errors.length,0,errors.join('\n'));
    const screenshots=process.env.DASHBOARD_SCREENSHOTS;
    if(screenshots) {
      fs.mkdirSync(screenshots,{recursive:true});
      await search.fill('');
      await page.waitForTimeout(700);
      await page.screenshot({path:path.join(screenshots,'dashboard-desktop.png'),fullPage:true});
      await page.setViewportSize({width:390,height:844});
      await page.getByRole('button',{name:'Abrir menu',exact:true}).click();
      await page.locator('#workspace-navigation').getByRole('button',{name:'Fechar menu'}).click();
      await page.getByRole('button',{name:'Adicionar vídeo',exact:true}).first().click();
      await page.getByRole('dialog').waitFor();
      await page.getByRole('dialog').getByRole('button',{name:'Fechar',exact:true}).click();
      await page.screenshot({path:path.join(screenshots,'dashboard-mobile.png'),fullPage:true});
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile layout must not overflow');
    }
    await page.setViewportSize({width:1440,height:1000});
    insert.run(1, source.id, 'estudio.criativo', 'https://www.instagram.com/reel/partial/', 'partial', 'Publicação parcial de teste', '', 'publishing', media, 'https://media.example.invalid/test.mp4', 42, null);
    const partial=d.getDb().prepare("SELECT id FROM reels WHERE instagram_id='partial'").get();
    d.updateReel(partial.id,{ig_post_id:'already-published-instagram'});
    d.updateSettings(1,{instagram_enabled:true,facebook_enabled:true});
    await search.fill('Publicação parcial de teste');
    await page.getByText('Publicação parcial de teste',{exact:true}).waitFor();
    const remaining=page.getByRole('button',{name:'Publicar',exact:true});
    assert.equal(await remaining.count(),1,'partially published video must allow publishing its remaining enabled destination');
    await remaining.click();
    await page.getByRole('dialog').waitFor();
    assert.equal(await page.getByRole('dialog').getByRole('checkbox',{name:/Instagram/}).count(),0,'completed destination must not be offered again');
    await page.getByRole('dialog').getByRole('checkbox',{name:/Facebook/}).waitFor();
    await page.getByRole('dialog').getByRole('button',{name:'Cancelar',exact:true}).click();
    const reviewJobs=[];
    for(let i=0;i<7;i++) {
      const job=queue.enqueue(1,'publish',i+1,{target:'facebook',manual:true});
      reviewJobs.push(job);
      queue.db.prepare("UPDATE pipeline_jobs SET status='needs_review',error_message=?,updated_at=? WHERE id=?").run(`Revisão pendente ${i+1}`,Date.now()-i,job.id);
    }
    await page.getByRole('button',{name:'Atualizar lista',exact:true}).click();
    await page.getByText('Revisão pendente 1',{exact:true}).waitFor();
    await page.getByRole('button',{name:/Ver todas as atividades/}).click();
    await page.getByText('Revisão pendente 7',{exact:true}).waitFor();
    const reviewRegion=page.getByRole('region',{name:'Atividade da automação',exact:true});
    await reviewRegion.getByRole('listitem').filter({hasText:'Revisão pendente 7'}).getByRole('button',{name:'Confirmar post existente',exact:true}).click();
    await page.getByRole('dialog').getByRole('textbox',{name:'ID do post'}).fill('verified-test-post');
    await page.getByRole('dialog').getByRole('button',{name:'Confirmar post existente',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    assert.equal(queue.get(reviewJobs[6].id,1).status,'queued');
    assert.equal(queue.db.prepare("SELECT post_id FROM pipeline_publications WHERE reel_id=? AND target='facebook'").get(7).post_id,'verified-test-post');
    await reviewRegion.getByRole('listitem').filter({hasText:'Revisão pendente 6'}).getByRole('button',{name:'Confirmei que não houve envio',exact:true}).click();
    await page.getByRole('dialog').getByRole('button',{name:'Autorizar nova tentativa',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    assert.equal(queue.get(reviewJobs[5].id,1).status,'queued');
    assert.equal(JSON.parse(queue.get(reviewJobs[5].id,1).payload).manual,true);
    await page.getByRole('button',{name:'Recolher atividades',exact:true}).click();
    await page.getByRole('button',{name:'Rodar agora',exact:true}).click();
    await page.getByRole('dialog').getByRole('button',{name:'Executar ciclo agora',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    assert.ok(queue.state('last_run:1'));
    assert.ok(queue.db.prepare("SELECT 1 FROM pipeline_jobs WHERE kind='discover'").get());
    await page.getByRole('button',{name:'Reprocessar falhas',exact:true}).click();
    await page.getByRole('dialog').getByRole('button',{name:'Reprocessar falhas',exact:true}).click();
    await page.getByRole('dialog').waitFor({state:'hidden'});
    assert.ok(queue.db.prepare("SELECT COUNT(*) n FROM pipeline_jobs WHERE kind='prepare'").get().n>5);
    await search.fill('');
    const productionResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/reels' && new URL(r.url()).searchParams.get('stage_group')==='processing');
    await page.getByRole('group',{name:'Filtrar por etapa'}).getByRole('button',{name:/^Em produção/}).click();
    const production=await (await productionResponse).json();
    assert.ok(production.data.reels.length>0);
    assert.ok(production.data.reels.every(r=>['downloading','downloaded','processing','processed','uploading','publishing'].includes(r.stage)));
    await page.getByRole('group',{name:'Filtrar por etapa'}).getByRole('button',{name:/^Todos/}).click();
    let failReads=true;
    await page.route('**/api/reels?**',route=> failReads ? route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({success:false,error:'Falha simulada de conexão'})}) : route.continue());
    await page.getByRole('button',{name:'Atualizar lista',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'Falha simulada de conexão'}).waitFor();
    failReads=false;
    await page.getByRole('button',{name:'Tentar novamente',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'Falha simulada de conexão'}).waitFor({state:'hidden'});
    await page.unroute('**/api/reels?**');
    let expired=true;
    await page.route('**/api/reels?**',route=>expired ? route.fulfill({status:401,contentType:'application/json',body:'{"success":false}'}) : route.continue());
    await page.getByRole('button',{name:'Atualizar lista',exact:true}).click();
    await page.getByRole('link',{name:'Entrar novamente',exact:true}).waitFor();
    expired=false;
    await page.getByRole('button',{name:'Atualizar lista',exact:true}).click();
    await page.getByRole('link',{name:'Entrar novamente',exact:true}).waitFor({state:'hidden'});
    await page.unroute('**/api/reels?**');
    let oldRequestStarted;
    const oldStarted=new Promise(resolve=>{oldRequestStarted=resolve;});
    let releaseOld;
    const oldRelease=new Promise(resolve=>{releaseOld=resolve;});
    await page.route('**/api/reels?**',async route=>{
      if(new URL(route.request().url()).searchParams.get('q')!=='resposta-atrasada') return route.continue();
      oldRequestStarted();
      await oldRelease;
      const old={...d.getReelById(1,1),caption:'Resposta antiga que não deve aparecer'};
      await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({success:true,data:{reels:[old],total:1,page:1,totalPages:1}})}).catch(()=>{});
    });
    await search.fill('resposta-atrasada');
    await oldStarted;
    await search.fill('Prévia da campanha');
    await previewCard.waitFor();
    releaseOld();
    await page.waitForTimeout(150);
    assert.equal(await page.getByText('Resposta antiga que não deve aparecer',{exact:true}).count(),0,'cancelled old search cannot overwrite current result');
    await page.unroute('**/api/reels?**');
    await page.locator('#workspace-navigation').getByRole('link',{name:'Fontes',exact:true}).click();
    await page.getByRole('heading',{name:'Fontes',exact:true}).waitFor();
    await page.locator('#workspace-navigation').getByRole('link',{name:'Configurações',exact:true}).click();
    await page.getByRole('heading',{name:'Configurações',exact:true}).waitFor();
    await page.locator('#workspace-navigation').getByRole('link',{name:'Painel',exact:true}).click();
    await page.getByRole('heading',{name:'Biblioteca de vídeos',exact:true}).waitFor();
    assert.equal(queue.db.prepare("SELECT COUNT(*) n FROM pipeline_jobs WHERE status='running'").get().n,0,'no test starts external execution');
    assert.equal(queue.state('paused'),'true');
    assert.equal(errors.length,0,errors.join('\n'));
    console.log('Dashboard browser smoke passed: playback, full search/pagination, grouped filters, add/modal focus+reset, publish/partial targets, process/delete409, batch retry, run/review, error/auth recovery, stale responses, mobile and navigation. Queue stayed paused; no external execution.');
  } finally {
    if(browser) await browser.close();
    server.kill('SIGTERM');
    await new Promise(r=>server.exitCode!==null?r():server.once('exit',r));
    queue.db.close();
    d.getDb().close();
    fs.rmSync(dir,{recursive:true,force:true});
  }
}
main().catch(e=>{console.error(e);process.exitCode=1;});
